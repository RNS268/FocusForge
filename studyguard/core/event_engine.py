# studyguard/core/event_engine.py

from __future__ import annotations

from collections import defaultdict
from typing import Any

from studyguard.core.config import DetectionSettings
from studyguard.core.events import AppEvent, EventBus, EventType
from studyguard.vision.results import DetectionResult


class EventEngine:
    """Turns noisy detector output into stable, debounced application events."""

    # Events that should not immediately fire on the first positive frame.
    DEFAULT_DURATION_THRESHOLDS = {
        EventType.DROWSINESS.value: "drowsy_seconds",
        EventType.LOOKING_AWAY.value: "looking_away_seconds",
        EventType.YAWN.value: "yawn_seconds",
        EventType.BAD_POSTURE.value: "posture_warning_seconds",
        EventType.USER_AWAY.value: "absence_seconds",
    }

    DEFAULT_COOLDOWNS = {
        EventType.DROWSINESS.value: 15.0,
        EventType.PHONE_DETECTED.value: 10.0,
        EventType.LOOKING_AWAY.value: 15.0,
        EventType.BAD_POSTURE.value: 20.0,
        EventType.YAWN.value: 20.0,
        EventType.EXCESSIVE_BLINKING.value: 20.0,
        EventType.USER_AWAY.value: 10.0,
    }

    # These events are generated by detectors only after they have already
    # performed their own temporal validation.
    IMMEDIATE_EVENTS = {
        EventType.PHONE_DETECTED.value,
        EventType.YAWN.value,
        EventType.EXCESSIVE_BLINKING.value,
    }

    def __init__(
        self,
        bus: EventBus,
        settings: DetectionSettings,
    ):
        self.bus = bus
        self.settings = settings

        # When each event became continuously active.
        self.active_since: dict[str, float] = {}

        # Events that have already been emitted during their current
        # continuous activation.
        self.was_active: set[str] = set()

        # Last time an event was emitted.
        self.last_event_at: dict[str, float] = defaultdict(
            lambda: -1e9
        )

        # Number of consecutive positive frames for each event.
        self.active_frames: dict[str, int] = defaultdict(int)

        # Number of consecutive negative frames.
        self.inactive_frames: dict[str, int] = defaultdict(int)

        # Last DetectionResult metadata for useful UI/debugging.
        self.last_results: dict[str, DetectionResult] = {}

    def process(
        self,
        result: DetectionResult,
        timestamp: float,
    ) -> list[AppEvent]:
        """
        Convert a detector result into a debounced AppEvent.

        The detector decides whether something is currently detected.
        The event engine decides whether that detection has persisted long
        enough to deserve an application-level alert.
        """
        event_name = result.event_type

        if not event_name:
            return []

        self.last_results[event_name] = result

        if not result.detected:
            self._reset_event(event_name)
            return []

        # Detection is active.
        if event_name not in self.active_since:
            self.active_since[event_name] = timestamp
            self.active_frames[event_name] = 0
            self.inactive_frames[event_name] = 0

        self.active_frames[event_name] += 1
        self.inactive_frames[event_name] = 0

        duration = max(
            0.0,
            timestamp - self.active_since[event_name],
        )

        threshold = self._duration_threshold(event_name)
        cooldown = self._cooldown(event_name)

        # Detector-level temporal validation can mark events such as YAWN,
        # PHONE_DETECTED, and EXCESSIVE_BLINKING as ready immediately.
        if event_name in self.IMMEDIATE_EVENTS:
            threshold = min(
                threshold,
                0.0,
            )

        enough_duration = duration >= threshold

        not_already_active = (
            event_name not in self.was_active
        )

        cooldown_complete = (
            timestamp
            - self.last_event_at[event_name]
            >= cooldown
        )

        should_emit = (
            enough_duration
            and not_already_active
            and cooldown_complete
        )

        if not should_emit:
            return []

        self.was_active.add(event_name)
        self.last_event_at[event_name] = timestamp

        event = self._create_event(
            event_name=event_name,
            timestamp=timestamp,
            duration=duration,
            result=result,
        )

        self.bus.publish(event)

        return [event]

    def _create_event(
        self,
        event_name: str,
        timestamp: float,
        duration: float,
        result: DetectionResult,
    ) -> AppEvent:
        """
        Build the application event while preserving detector metadata.
        """
        metadata: dict[str, Any] = dict(
            result.metadata or {}
        )

        metadata.update(
            {
                "event_name": event_name,
                "active_duration": duration,
                "active_frames": self.active_frames.get(
                    event_name,
                    0,
                ),
                "event_threshold": self._duration_threshold(
                    event_name,
                ),
                "event_cooldown": self._cooldown(
                    event_name,
                ),
            }
        )

        return AppEvent(
            event_type=EventType(event_name),
            timestamp=timestamp,
            duration=duration,
            confidence=result.confidence,
            metadata=metadata,
        )

    def _reset_event(
        self,
        event_name: str,
    ) -> None:
        """
        Reset the continuous activation state.

        A later detection can therefore generate a fresh event once its
        duration/cooldown requirements are satisfied.
        """
        self.active_since.pop(
            event_name,
            None,
        )

        self.was_active.discard(
            event_name,
        )

        self.active_frames.pop(
            event_name,
            None,
        )

        self.inactive_frames[event_name] += 1

    def _duration_threshold(
        self,
        event_name: str,
    ) -> float:
        """
        Resolve the persistence threshold from DetectionSettings.

        Unknown events default to zero seconds rather than crashing the
        application.
        """
        setting_name = self.DEFAULT_DURATION_THRESHOLDS.get(
            event_name,
        )

        if setting_name is None:
            if event_name == EventType.PHONE_DETECTED.value:
                return 0.2

            if event_name == EventType.EXCESSIVE_BLINKING.value:
                return 0.0

            return 0.0

        try:
            return max(
                0.0,
                float(
                    getattr(
                        self.settings,
                        setting_name,
                        0.0,
                    )
                ),
            )
        except (TypeError, ValueError):
            return 0.0

    def _cooldown(
        self,
        event_name: str,
    ) -> float:
        """
        Return the minimum time between repeated alerts.
        """
        return max(
            0.0,
            float(
                self.DEFAULT_COOLDOWNS.get(
                    event_name,
                    0.0,
                )
            ),
        )

    def clear(self) -> None:
        """
        Clear all temporal state.

        Useful when the user starts a new study session or when the camera
        pipeline is restarted.
        """
        self.active_since.clear()
        self.was_active.clear()
        self.last_event_at.clear()
        self.active_frames.clear()
        self.inactive_frames.clear()
        self.last_results.clear()